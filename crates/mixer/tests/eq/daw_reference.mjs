// Prints reference.rs: what another_synth's post-fx equaliser (its TypeScript, run as it is)
// computes, for the mixer's equaliser to be checked against.
//
//   node crates/mixer/tests/eq/daw_reference.mjs [path to another_synth] > crates/mixer/tests/eq/reference.rs
//
// Needs Node 22.18 or newer (it imports the .ts file directly). The checkout defaults to
// ~/src/rust/another_synth. The numbers are in the test, so nothing needs Node or the DAW to
// run the tests; run this only when the DAW's equaliser changes.
import { homedir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.argv[2] ?? join(homedir(), 'src', 'rust', 'another_synth');
const math = await import(
  pathToFileURL(join(root, 'packages', 'tracker-playback', 'src', 'postfx', 'eq-math.ts')).href
);

// 1 kHz-centred checks and every band centre, in between and beyond.
const FREQS = [
  20, 31, 40, 50, 62, 80, 100, 125, 160, 200, 250, 315, 400, 500, 630, 800, 1000, 1250, 1600,
  2000, 2500, 3150, 4000, 5000, 6300, 8000, 10000, 12500, 16000, 18000, 20000,
];
const graphic = [
  ...math.EQ_PRESETS.map((p) => [p.id, [...p.gainsDb]]),
  ['single-boost-1k', [0, 0, 0, 0, 0, 12, 0, 0, 0, 0]],
  ['single-cut-125', [0, 0, -12, 0, 0, 0, 0, 0, 0, 0]],
  ['alternating', [12, -12, 12, -12, 12, -12, 12, -12, 12, -12]],
  ['flat-six', [6, 6, 6, 6, 6, 6, 6, 6, 6, 6]],
  ['nearly-flat', [0.02, -0.03, 0.01, 0, 0.04, 0, 0, -0.02, 0, 0.03]],
  ['over-range', [20, -20, 3, 0, 0, 0, 0, 0, -30, 40]],
];
const raw = [
  ['raw-bass', [6, 6, 4, 2, 0, 0, 0, 0, 0, 0]],
  ['raw-smile', [5, 4, 2, 0, -3, -3, 0, 2, 4, 5]],
  ['raw-mixed', [-12, 9, -7, 3, 0, 12, -4, 8, -9, 5]],
];

const f = (x) => (Number.isInteger(x) ? `${x}.0` : String(x));
const list = (xs) => `[${xs.map(f).join(', ')}]`;
const out = [];
out.push('//! Generated by daw_reference.mjs from another_synth\'s eq-math.ts: do not edit.');
out.push('#![allow(dead_code)]');
out.push('');
out.push(`/// The frequencies the responses are given at, Hz.`);
out.push(`pub const FREQS: [f32; ${FREQS.length}] = ${list(FREQS)};`);
out.push('');
out.push('/// A graphic-mode case: the gains set, the gains the DAW applies (`eqEffectiveGains`) and');
out.push('/// the response of those at 48 kHz (`eqResponseDb`), in dB at `FREQS`.');
out.push('pub struct Graphic {');
out.push('    pub name: &\'static str,');
out.push('    pub set: [f32; 10],');
out.push('    pub applied: [f64; 10],');
out.push(`    pub response: [f64; ${FREQS.length}],`);
out.push('}');
out.push('');
out.push(`pub const GRAPHIC: [Graphic; ${graphic.length}] = [`);
for (const [name, gains] of graphic) {
  const applied = math.eqEffectiveGains({ gainsDb: gains }).gainsDb;
  const response = Array.from(math.eqResponseDb({ gainsDb: applied }, FREQS, 48000));
  out.push('    Graphic {');
  out.push(`        name: ${JSON.stringify(name)},`);
  out.push(`        set: ${list(gains)},`);
  out.push(`        applied: ${list(applied)},`);
  out.push(`        response: ${list(response)},`);
  out.push('    },');
}
out.push('];');
out.push('');
out.push('/// A case with the band gains applied as they are (parametric mode, the DAW\'s bands).');
out.push('pub struct Raw {');
out.push('    pub name: &\'static str,');
out.push('    pub gains: [f32; 10],');
out.push(`    pub response: [f64; ${FREQS.length}],`);
out.push('}');
out.push('');
out.push(`pub const RAW: [Raw; ${raw.length}] = [`);
for (const [name, gains] of raw) {
  const response = Array.from(math.eqResponseDb({ gainsDb: gains }, FREQS, 48000));
  out.push('    Raw {');
  out.push(`        name: ${JSON.stringify(name)},`);
  out.push(`        gains: ${list(gains)},`);
  out.push(`        response: ${list(response)},`);
  out.push('    },');
}
out.push('];');
console.log(out.join('\n'));
